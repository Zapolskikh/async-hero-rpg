from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def catalog():
    source = (ROOT / 'scripts/data/talents.gd').read_text(encoding='utf-8')
    talents = json.JSONDecoder().raw_decode(source.split('const TALENTS := ', 1)[1])[0]
    source = (ROOT / 'scripts/data/db.gd').read_text(encoding='utf-8').split('const SPELLS := {', 1)[1].split('\n}\n', 1)[0]
    spells = {}
    for line in source.splitlines():
        match = re.match(r'\s*"([^"]+)":\s*({.*}),?\s*$', line)
        if match:
            spells[match[1]] = json.loads(match[2])
    return talents, spells


